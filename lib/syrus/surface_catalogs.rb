# frozen_string_literal: true

require "fileutils"

module Syrus
  module SurfaceCatalogs
    CATALOGS = {
      user_api: "website/src/content/docs/generated/user-api-catalog.md",
      admin_api: "docs/engineering/architecture/admin_api_catalog.md",
      mcp: "config/syrus_docs/mcp_tool_catalog.md",
      cli: "website/src/content/docs/generated/cli-catalog.md",
      families: "docs/engineering/conventions/plugins/family-catalog.md"
    }.freeze

    def self.render_all(root: Rails.root)
      {
        user_api: render_user_api,
        admin_api: render_admin_api,
        mcp: render_mcp,
        cli: render_cli(root: root),
        families: render_families
      }
    end

    def self.write_all!(root: Rails.root)
      render_all(root: root).each do |key, body|
        path = root.join(CATALOGS.fetch(key))
        FileUtils.mkdir_p(path.dirname)
        File.write(path, body)
      end
    end

    def self.committed(root: Rails.root)
      CATALOGS.transform_values do |relative_path|
        path = root.join(relative_path)
        File.exist?(path) ? File.read(path) : nil
      end
    end

    def self.render_user_api
      with_frontmatter(
        title: "User API Catalog",
        description: "Generated endpoint catalog for the Syrus user API.",
        body: render_route_catalog(
          title: "User API catalog",
          intro: "Generated catalog of core `/api/v1/app/*` endpoints, excluding the UI-serving `/api/v1/app/admin/*` namespace. Plugin-owned endpoints belong in the owning plugin's docs.",
          routes: api_routes(prefix: "/api/v1/app", exclude_prefixes: [ "/api/v1/app/admin" ])
        )
      )
    end

    def self.render_admin_api
      render_route_catalog(
        title: "Admin API catalog",
        intro: "Generated catalog of core token-only `/api/v1/admin/*` operator endpoints. Plugin-owned endpoints belong in the owning plugin's docs.",
        routes: api_routes(prefix: "/api/v1/admin")
      )
    end

    def self.render_mcp
      entries = McpToolRegistry.summaries.sort_by { |entry| [ entry[:surface].to_s, entry[:tier].to_s, entry[:tool_name].to_s ] }
      rows = entries.map do |entry|
        [
          "`#{entry.fetch(:tool_name)}`",
          entry.fetch(:surface),
          entry[:tier].presence || "-",
          entry.fetch(:mutation) ? "write" : "read",
          entry.fetch(:admin_only) ? "yes" : "no",
          Array(entry[:required_roles]).presence&.map { |role| "`#{role}`" }&.join(", ") || "-",
          Array(entry[:step_kinds]).presence&.map { |kind| "`#{kind}`" }&.join(", ") || "-",
          entry[:capability].present? ? "`#{entry[:capability]}`" : "-",
          entry[:feature_flag].present? ? "`#{entry[:feature_flag]}`" : "-",
          permission_class(entry[:descriptor])
        ]
      end

      <<~MD
        # MCP tool catalog

        <!-- Generated by bin/surface-catalogs. Do not edit by hand. -->

        Generated catalog of MCP tools registered through `McpToolRegistry`.

        The Permission column is each tool's consequence classification on that
        surface (see [Permission authority](permission_authority.md)):

        - **essential** -- consequence-free agent work. Always allowed: it is
          evaluated and audited, but no rule, preset, lease or confirmation request
          can block it. `default: allow` is not essential; internal persistence
          alone is not a consequence barrier.
        - **gated** -- crosses a consequence barrier, named by its effects.
        - **deniable** -- no barrier effect, but deniable for the named reason.

        | Tool | Surface | Tier | Mode | Admin | Roles | Step kinds | Capability | Feature flag | Permission |
        |---|---|---|---|---|---|---|---|---|---|
        #{rows.map { |row| "| #{row.join(' | ')} |" }.join("\n")}
      MD
    end

    def self.permission_class(descriptor)
      return "-" unless descriptor
      return "essential" if descriptor.essential?
      return "gated (#{descriptor.barrier_effects.join(', ')})" if descriptor.barrier_effects.any?

      "deniable (#{descriptor.deniable_reason.to_s.tr('_', ' ')})"
    end

    def self.render_cli(root:)
      result = capture([ *go_command(root: root), "run", "./catalog" ], root: root, env: { "GOWORK" => "off" })
      raise "CLI catalog generation failed:\n#{result.stderr}" unless result.success?

      with_frontmatter(
        title: "CLI Command Catalog",
        description: "Generated command and flag catalog for the Syrus CLI.",
        body: result.stdout
      )
    end

    def self.render_families(definitions: Syrus::Plugin::Family.all, manifests: Syrus::PluginRegistry.all_plugins)
      declarations = manifests.flat_map do |manifest|
        Array(manifest.family_provides).map { |declaration| [ manifest.name, declaration ] }
      end
      sections = definitions.sort_by(&:name).map do |family|
        capability_rows = family.capabilities.values.sort_by(&:name).map do |capability|
          "| `#{capability.name}` | `#{capability.composition}` | `#{capability.absent.inspect}` | `#{capability.decline.inspect}` | `#{capability.tier}` | `#{context_label(capability.context)}` | `#{capability.return_contract.description}` |"
        end
        provider_rows = declarations.filter_map do |plugin, declaration|
          next unless declaration.family == family.name
          stable = declaration.implements.map { |name| "`#{name}`" }.join(", ").presence || "-"
          provisional = declaration.provisional.map { |name| "`#{name}`" }.join(", ").presence || "-"
          "| `#{plugin}` | `#{declaration.provider}` | #{declaration.key ? "`#{declaration.key}`" : "-"} | #{stable} | #{provisional} |"
        end.sort
        <<~MD
          ## `#{family.name}`

          Shape: `#{family.shape}`. Required core: #{family.required_core.map { |name| "`#{name}`" }.join(", ")}.

          | Capability | Composition | Absent behavior | Provider decline | Tier | Context | Return shape |
          |---|---|---|---|---|---|---|
          #{capability_rows.join("\n")}

          For keyed capabilities, absent behavior applies when no provider matches the requested key and raises `Dispatch::MissingKey`; a matched provider's decline value is separate.

          | Plugin | Provider | Key | Stable capabilities | Provisional capabilities |
          |---|---|---|---|---|
          #{provider_rows.presence || "| - | - | - | - | - |"}
        MD
      end
      <<~MD
        # Plugin capability family catalog

        <!-- Generated by bin/surface-catalogs. Do not edit by hand. -->

        Families are defined by core and implementations are read from plugin manifests.
        A stable capability requires at least two independent in-tree implementations
        and a generated contract test; all other capabilities are provisional.

        #{sections.presence&.join("\n")&.rstrip || "No capability families are currently defined."}
      MD
    end

    def self.go_command(root: Rails.root)
      return [ "go" ] if command_available?([ "go", "version" ], root: root, env: { "GOWORK" => "off" })
      return [ "mise", "exec", "go@1.26.5", "--", "go" ] if command_available?([ "mise", "--version" ], root: root)

      [ "go" ]
    end

    private_class_method def self.context_label(context)
      context.respond_to?(:name) ? context.name : context.to_s
    end

    private_class_method def self.command_available?(command, root:, env: {})
      capture(command, root: root, env: env).success?
    rescue Errno::ENOENT
      false
    end

    private_class_method def self.capture(command, root:, env: {})
      ProcessRunner.new(
        env: ProcessRunner.forwarded_env(%w[PATH HOME GOPATH GOMODCACHE]).merge(env),
        command: command, mounts: ProcessRunner.mounts(root.join("cli")),
        network: "grader", timeout: 2.minutes, kind: "generate"
      ).capture
    end

    def self.api_routes(prefix:, exclude_prefixes: [])
      core_routes(prefix: prefix, exclude_prefixes: exclude_prefixes)
    end

    def self.core_routes(prefix:, exclude_prefixes:)
      Rails.application.routes.routes.filter_map do |route|
        path = route.path.spec.to_s.sub("(.:format)", "")
        next unless path.start_with?(prefix)
        next if exclude_prefixes.any? { |excluded| path.start_with?(excluded) }
        next if path.include?("*plugin_route")

        {
          owner: "core",
          verb: route.verb.to_s,
          path: path,
          controller: "#{route.defaults[:controller]}##{route.defaults[:action]}"
        }
      end
    end

    def self.render_route_catalog(title:, intro:, routes:)
      rows = routes.sort_by { |route| [ route.fetch(:path), route.fetch(:verb), route.fetch(:owner) ] }.map do |route|
        "| #{route.fetch(:owner)} | #{route.fetch(:verb)} | `#{route.fetch(:path)}` | `#{route.fetch(:controller)}` |"
      end

      <<~MD
        # #{title}

        <!-- Generated by bin/surface-catalogs. Do not edit by hand. -->

        #{intro}

        | Owner | Method | Path | Handler |
        |---|---|---|---|
        #{rows.join("\n")}
      MD
    end

    def self.with_frontmatter(title:, description:, body:)
      <<~MD
        ---
        title: #{title}
        description: #{description}
        ---

        #{body}
      MD
    end
  end
end
