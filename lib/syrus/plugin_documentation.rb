module Syrus
  class PluginDocumentation
    ROOT = Rails.root
    HOST_API_PATH = ROOT.join("docs/engineering/conventions/plugins/host-api.md")
    PLUGIN_SPEC_PATH = ROOT.join("docs/engineering/conventions/plugins/plugin-spec.md")
    GENERATED_NOTICE = "<!-- Generated by bin/generate-plugin-docs; do not edit by hand. -->"

    def host_api
      lines = [ GENERATED_NOTICE, "", "# Plugin host API", "",
        "These are the supported core APIs an external plugin may call. Anything not listed is internal.", "" ]
      public_entries.group_by(&:category).sort.each do |category, entries|
        lines.concat([ "## #{category}", "" ])
        entries.sort_by(&:name).each do |entry|
          lines.concat([ "### `#{entry.name}`", "", "Tier: `#{entry.tier}`. Since Syrus #{entry.since}. #{entry.contract}", "" ])
          next if entry.members.empty?

          entry.members.sort.each do |kind, members|
            lines << "- Supported #{kind} members: #{members.sort.map { |member| "`#{member}`" }.join(', ')}"
          end
          lines << ""
        end
      end
      lines.join("\n").rstrip + "\n"
    end

    def plugin_spec
      lines = [ GENERATED_NOTICE, "", "# Syrus plugin specification", "",
        "Paste this file as a complete host contract when asking an LLM to write a Syrus plugin.", "",
        "## Manifest schema", "" ]
      Syrus::PluginApi::Definition::MANIFEST_SCHEMA.sort.each do |key, description|
        lines << "- `#{key}` — #{description}"
      end
      lines.concat([ "", "`frontend` accepts `bundle`, `css`, and `i18n`; locale globs must resolve under `app/frontend/i18n/locales/{en,de,la}/`. `cli_commands` entries require `path`, `summary`, and `handler`, and may declare typed `arguments` and `flags`.", "",
        "## Extension points", "" ])
      Syrus::PluginRegistry::EXTENSION_POINTS.sort.each do |point|
        interface = Syrus::PluginRegistry::INTERFACE_FOR.fetch(point).call
        relative = "../../../../lib/syrus/plugin/#{point}.rb"
        lines << "- `#{point}` — #{interface_summary(point)} See [`#{interface.name}`](#{relative}) for the interface contract."
      end
      lines.concat([ "", "## Public host surface", "",
        "The supported constants and members are reproduced below; the grouped human reference is [Plugin host API](host-api.md).", "" ])
      public_entries.sort_by(&:name).each do |entry|
        members = entry.members.sort.flat_map { |kind, names| names.sort.map { |name| "#{kind}:`#{name}`" } }
        suffix = members.empty? ? "" : " Supported: #{members.join(', ')}."
        lines << "- `#{entry.name}` (`#{entry.tier}`, since #{entry.since}) — #{entry.contract}#{suffix}"
      end
      lines.concat([ "", "## Packaging and testing", "",
        "Plugins are trusted, in-process Rails Engine gems, not sandboxes. External gemspecs may depend only on Rails; use Ruby's standard library and the public host surface instead of third-party gems. Package prebuilt frontend assets and declare them with `frontend`. A plugin install or code change requires a Syrus restart.", "",
        "Tests are required. Test each provider contract and plugin behavior, and include relocation/package coverage for external plugins. User-visible copy must be localized in English, German, and Latin.", "",
        "## Mistakes to avoid", "",
        "- Do not call unlisted core constants or members, or use `legacy` APIs from an external plugin.",
        "- Do not put implementation classes in `provides`; register class-name strings that implement the linked interface.",
        "- Do not add third-party Ruby gem dependencies or assume Syrus installs them.",
        "- Do not run migrations when enabling a plugin; migrations run during deployment.",
        "- Do not omit tests, the three locale bundles, `requires_syrus`, or the restart step.", "" ])
      body = lines.join("\n").rstrip + "\n"
      body + "\nGenerated content size (excluding this line): #{body.bytesize} bytes, #{body.scan(/\S+/).size} words.\n"
    end

    def write!
      HOST_API_PATH.write(host_api)
      PLUGIN_SPEC_PATH.write(plugin_spec)
    end

    private

    def public_entries = Syrus::PluginHostSurface.new.public_entries

    def interface_summary(point)
      path = ROOT.join("lib/syrus/plugin/#{point}.rb")
      comments = path.readlines.drop_while { |line| !line.match?(/^    #/) }
        .take_while { |line| line.match?(/^    #/) }
        .map { |line| line.sub(/^    # ?/, "").strip }
      paragraph = comments.slice_before(&:empty?).first.to_a.reject(&:empty?).join(" ")
      sentence = paragraph.split(/(?<=[.!?])\s+/, 2).first.to_s
      if sentence.empty? || sentence.end_with?(":")
        "Providers implement the registered #{point.to_s.tr('_', ' ')} contract."
      else
        sentence
      end
    end
  end
end
