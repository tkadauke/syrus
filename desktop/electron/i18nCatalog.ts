export function normalizeLocale(locale: string | null | undefined): Locale {
  const baseLocale = locale?.trim().toLowerCase().split(/[-_]/)[0] as Locale | undefined
  return baseLocale && supportedLocales.includes(baseLocale) ? baseLocale : "en"
}

export function translate(locale: Locale, key: string, values: Record<string, string | number | null | undefined> = {}) {
  const localizedMessages: Partial<Record<string, string>> = messages[locale]
  const englishMessages: Partial<Record<string, string>> = messages.en
  const template = localizedMessages[key] ?? englishMessages[key] ?? key
  return template.replace(/\{\{(\w+)\}\}/g, (_match: string, name: string) => String(values[name] ?? ""))
}
