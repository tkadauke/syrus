require "rails_helper"

RSpec.describe Syrus::PluginDocumentation do
  it "keeps the generated host API reference current" do
    expect(described_class::HOST_API_PATH.read).to eq(described_class.host_api),
      "Plugin host API documentation is stale; run bin/generate-plugin-docs"
  end

  it "keeps the generated single-file plugin specification current" do
    expect(described_class::PLUGIN_SPEC_PATH.read).to eq(described_class.plugin_spec),
      "Plugin specification is stale; run bin/generate-plugin-docs"
  end

  it "keeps generated per-family references current" do
    committed = described_class::FAMILY_REFERENCE_ROOT.glob("*.md").to_h do |path|
      [ path.basename(".md").to_s.to_sym, path.read ]
    end
    expect(committed).to eq(described_class.family_references),
      "Plugin family references are stale; run bin/generate-plugin-docs"
  end

  it "documents requires_syrus as gemspec string metadata" do
    expect(described_class.plugin_spec).to include('metadata["requires_syrus"] = ">= 0.1.16"')
  end

  it "documents every accepted manifest key and registered extension point" do
    spec = described_class.plugin_spec
    Syrus::PluginApi::Definition::MANIFEST_KEYS.each { |key| expect(spec).to include("`#{key}`") }
    Syrus::PluginRegistry::EXTENSION_POINTS.each { |point| expect(spec).to include("`#{point}`") }
    expect(described_class::MANIFEST_DESCRIPTIONS.keys).to contain_exactly(*Syrus::PluginApi::Definition::MANIFEST_KEYS)
    expect(Syrus::PluginRegistry::EXTENSION_POINT_DESCRIPTIONS.keys).to contain_exactly(*Syrus::PluginRegistry::EXTENSION_POINTS)
    expect(Syrus::PluginRegistry::EXTENSION_POINT_DESCRIPTIONS.values).to all(match(/\A\S.*[.!?]\z/))
  end


  it "includes capability families in the compact plugin specification" do
    expect(described_class.plugin_spec).to include("## Capability families")
  end

  it "documents only the public host facades" do
    host_api = described_class.host_api
    plugin_spec = described_class.plugin_spec

    Syrus::Host.apis.each do |api|
      expect(host_api).to include("### `#{api.name}`")
      expect(plugin_spec).to include("- `#{api.name}` (since #{api.since})")
    end
    expect(host_api).not_to include("Legacy compatibility APIs")
    expect(plugin_spec).not_to include("legacy core constants")
    expect(host_api).not_to include("Tier: `public`")
  end

  it "records the exact generated byte size" do
    spec = described_class.plugin_spec
    expect(spec).to include("Size: #{spec.bytesize} bytes")
  end
end
